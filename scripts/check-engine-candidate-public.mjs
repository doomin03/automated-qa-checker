// Run only for the independently installed candidate accepted by management.
import assert from 'node:assert/strict';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {dirname, resolve, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [receiptPath, expectedVersion, expectedSha, ...extra] = process.argv.slice(2);
assert(receiptPath && /^0\.1\.0-alpha\.[1-9][0-9]*$/.test(expectedVersion ?? '') && /^[a-f0-9]{64}$/.test(expectedSha ?? '') && !extra.length, 'Explicit receipt/version/hash required');
const receipt = JSON.parse(await readFile(receiptPath));
assert.equal(receipt.engineVersion, expectedVersion); assert.equal(receipt.packageSha256, expectedSha);
const manifest = JSON.parse(await readFile(receipt.manifestPath));
assert.equal(manifest.engineVersion, expectedVersion); assert.equal(manifest.sha256, expectedSha);
for (const [path, sha] of Object.entries(manifest.files)) assert.equal(createHash('sha256').update(await readFile(join(receipt.packageRoot, path))).digest('hex'), sha);
const directory = dirname(receipt.manifestPath);
const output = resolve(root, 'artifacts/engine-refactor', expectedVersion, expectedSha); await mkdir(output, {recursive: true});
const good = join(directory, 'public-valid.mts'), bad = join(directory, 'public-invalid.mts');
await writeFile(good, `import {parseSource,compileBlueprint,executeBlueprint,blueprintXml,type Blueprint,type RunnerAdapter} from 'automated-qa-engine';
import {PlaywrightAdapter} from 'automated-qa-engine/playwright';
import {AppiumAdapter} from 'automated-qa-engine/appium';
declare const blueprint: Blueprint;
const adapter:RunnerAdapter=new PlaywrightAdapter();
const native:RunnerAdapter=new AppiumAdapter({endpoint:'http://127.0.0.1:4723',capabilities:{'appium:automationName':'UiAutomator2','appium:udid':'fixture','appium:deviceName':'fixture'}});
compileBlueprint(parseSource(blueprintXml(blueprint),'xml'));
void executeBlueprint(blueprint,{adapter,timeoutMs:1000});void native;
`, {flag: 'wx'});
await writeFile(bad, `import {parseSource,executeBlueprint} from 'automated-qa-engine';
import {AppiumAdapter} from 'automated-qa-engine/appium';
parseSource(42); executeBlueprint({}, {adapter:42}); new AppiumAdapter({});
`, {flag: 'wx'});
function tsc(file) {
  return spawnSync(process.execPath, [resolve(root, 'node_modules/typescript/bin/tsc'), '--noEmit', '--strict', '--module', 'NodeNext', '--moduleResolution', 'NodeNext', '--target', 'ES2022', '--lib', 'ES2022,DOM', file], {cwd: directory, encoding: 'utf8', windowsHide: true, timeout: 30000, maxBuffer: 2 * 1024 * 1024});
}
const valid = tsc(good), invalid = tsc(bad);
await writeFile(join(output, 'types-valid.log'), `${valid.stdout ?? ''}${valid.stderr ?? ''}`);
await writeFile(join(output, 'types-invalid.log'), `${invalid.stdout ?? ''}${invalid.stderr ?? ''}`);
assert.equal(valid.status, 0, 'Valid public TypeScript consumer failed');
assert.equal(invalid.status, 2, 'Invalid public calls must be rejected by TypeScript');
assert.match(invalid.stdout, /public-invalid\.mts/); assert.match(invalid.stdout, /TS(2322|2345)/);
const smoke = join(directory, 'public-exports.mjs');
await writeFile(smoke, `import assert from 'node:assert/strict';import {readFile} from 'node:fs/promises';
import * as api from 'automated-qa-engine';import * as web from 'automated-qa-engine/playwright';import * as mobile from 'automated-qa-engine/appium';
for(const name of ['parseSource','loadBlueprint','validateSchema','compileBlueprint','executeBlueprint','QaError','listPresets','expandPreset','blueprintXml','expandAuthoring','parseAuthoringSource','authoringXml'])assert.equal(typeof api[name],'function');
assert.equal(typeof web.PlaywrightAdapter,'function');assert.equal(typeof mobile.AppiumAdapter,'function');assert.equal(api.ENGINE_VERSION,process.argv[2]);
const blueprint=JSON.parse(await readFile(new URL('./node_modules/automated-qa-engine/examples/login.qa.json',import.meta.url)));
const fromJson=api.compileBlueprint(blueprint),fromXml=api.compileBlueprint(api.parseSource(api.blueprintXml(blueprint),'xml'));
assert.equal(fromJson.blueprintSnapshotHash,fromXml.blueprintSnapshotHash);
console.log(JSON.stringify({exports:Object.keys(api),xmlHash:fromXml.blueprintSnapshotHash,execution:false}));
`, {flag: 'wx'});
const exported = spawnSync(process.execPath, [smoke, expectedVersion], {cwd: directory, encoding: 'utf8', windowsHide: true, timeout: 15000, maxBuffer: 1048576});
await writeFile(join(output, 'public-exports.log'), `${exported.stdout ?? ''}${exported.stderr ?? ''}`);
assert.equal(exported.status, 0, 'Installed public exports failed');
const proof = {engineVersion: expectedVersion,packageSha256:expectedSha,validTypecheckExit:valid.status,invalidTypecheckExit:invalid.status,exports:JSON.parse(exported.stdout),internalDeepImports:false};
await writeFile(join(output, 'public-surface.json'), JSON.stringify(proof,null,2)+'\n');console.log(JSON.stringify(proof));
