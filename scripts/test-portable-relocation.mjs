import {readFile,writeFile,mkdtemp,cp,mkdir,open} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {tmpdir} from 'node:os';
import {resolve,join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const label=process.argv[2]??'relocation';
if(!/^[a-z0-9-]+$/.test(label))throw Error('Invalid evidence label');
const pin=JSON.parse(await readFile(join(root,'apps/app/engine-runtime-pin.json')));
const latest=JSON.parse(await readFile(join(root,'.local/portable-runtime',pin.engineVersion,pin.sha256,'latest.json')));
const destination=await mkdtemp(join(tmpdir(),'QA 이동 배포 '));
await cp(join(latest.destination,'runtime'),join(destination,'runtime'),{recursive:true,errorOnExist:true,force:false});
await cp(join(latest.destination,'portable-runtime.json'),join(destination,'portable-runtime.json'));
const artifacts=join(root,'artifacts/portable-runtime');await mkdir(artifacts,{recursive:true});
const log=join(artifacts,`${label}-test.log`);const handle=await open(log,'wx');
const command=[join(root,'scripts/flutter.mjs'),'test','test/portable_engine_test.dart','--concurrency=1'];
const started=new Date().toISOString();
const child=spawn(process.execPath,command,{cwd:root,env:{...process.env,QA_PORTABLE_TEST_ROOT:destination,QA_PORTABLE_TEST_LABEL:label},stdio:['ignore',handle.fd,handle.fd],windowsHide:true});
const code=await new Promise((res,rej)=>{child.on('error',rej);child.on('close',res);});await handle.close();
const result={started,finished:new Date().toISOString(),command,exitCode:code,destination,source:latest.destination,log};
await writeFile(join(artifacts,`${label}-test.json`),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));process.exitCode=code??1;
