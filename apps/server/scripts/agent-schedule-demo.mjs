import 'reflect-metadata';
import { randomUUID } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, join, isAbsolute } from 'node:path';
import { NestFactory } from '@nestjs/core';
import { AppModule } from '../dist/src/app.module.js';
import { PlatformService } from '../dist/src/modules/platform/platform.service.js';
import { AgentService } from '../dist/src/modules/agent/agent.service.js';
import { SuiteService } from '../dist/src/modules/suite/suite.service.js';
import { SchedulerService } from '../dist/src/modules/scheduler/scheduler.service.js';
import { demoIdentities } from './agent-demo-identities.mjs';
const root = resolve(import.meta.dirname, '../../..');
const [inputFile, tokenFile] = process.argv.slice(2);
if (process.env.NODE_ENV === 'production' || !isAbsolute(inputFile ?? '') || !isAbsolute(tokenFile ?? '')) throw new Error('Usage: local agent-schedule-demo.mjs ABS_INPUT_JSON ABS_MANAGER_TOKEN_FILE');
const name = process.env.QA_AGENT_DEMO_NAME ?? 'agent-demo-alpha6-candidate2';
if (!/^[A-Za-z0-9_-]{1,64}$/.test(name)) throw new Error('Invalid demo directory');
const directory = join(root, '.local', name), input = JSON.parse(await readFile(inputFile, 'utf8'));
const token = (await readFile(tokenFile, 'utf8')).trim(), expected = (await readFile(join(directory, 'manager-token.txt'), 'utf8')).trim();
const identities = await demoIdentities(directory, expected);
const app = await NestFactory.createApplicationContext(AppModule, { logger: false });
try {
  const platform = app.get(PlatformService);
  await platform.start({ mode:'local',dataDir:join(directory,'data'),identities,engineCli:process.env.QA_ENGINE_CLI,engineManifest:process.env.QA_ENGINE_MANIFEST });
  const user = platform.authenticate(`Bearer ${token}`); platform.authorize(user,'demo','qa_manager');
  const agents = app.get(AgentService); agents.start(false);
  const suites = app.get(SuiteService); suites.start(); agents.registerSuiteResolver(suites.resolvePublished.bind(suites));
  const scheduler = app.get(SchedulerService); scheduler.start(false);
  const agentId = 'scheduler-worker', resourceKey = 'web-slot-scheduler';
  const capabilities = { platforms:['web'],actions:['launch','tap','input','assertText','screenshot'] };
  const provisioned = agents.provision(user,{agentId,projectIds:['demo'],resourceKeys:[resourceKey],capabilities});
  const agentTokenFile = join(directory,'scheduler-token.txt'); await writeFile(agentTokenFile,provisioned.token,{flag:'wx',mode:0o600});
  const suffix = randomUUID(), draft = await platform.createDraft(user,'demo',{packageId:`schedule-${suffix}`,title:'Published scheduled local fixture',xml:input.xml,dependencies:[]});
  platform.review('demo-reviewer','demo',draft.id);
  const version = await platform.publish(user,'demo',draft.id,'1.0.0',suffix);
  const suiteDraft = suites.create(user,'demo',{packageId:`suite-${suffix}`,title:'Scheduled published Suite',stopOnFailure:true,cases:[{caseId:'scheduled-case',versionId:version.id,sha256:version.sha256}]});
  suites.review('demo-reviewer','demo',suiteDraft.id);
  const suite = suites.publish(user,'demo',suiteDraft.id,'1.0.0',suffix); suites.pin(user,'demo',suite.id,suite.sha256);
  const due = new Date(Math.ceil((Date.now()+60000)/60000)*60000);
  const policy = {resourceKey,platform:'web',allowedOrigins:[input.targetOrigin ?? 'http://127.0.0.1:4317'],nativeApps:[],secretRefs:[],allowProduction:false};
  const schedule = await scheduler.create(user,'demo',{versionId:null,suiteVersionId:suite.id,sha256:suite.sha256,executionPolicy:policy,timezone:'UTC',weekdays:[due.getUTCDay()||7],localTime:due.toISOString().slice(11,16),latenessSeconds:300,enabled:true});
  scheduler.tick(); scheduler.tick();
  const config = JSON.parse(await readFile(join(directory,'agent-config.json'),'utf8'));
  const configFile = join(directory,'scheduler-config.json');
  await writeFile(configFile,JSON.stringify({...config,agentId,stateDir:join(directory,'scheduler-engine-state'),resources:{[resourceKey]:{platform:'web',allowedOrigins:policy.allowedOrigins,nativeApps:[],secretRefs:[],actions:capabilities.actions,allowProduction:false}}},null,2)+'\n');
  const record = {scheduleId:schedule.id,suiteVersionId:suite.id,suiteSha256:suite.sha256,blueprintVersionId:version.id,dueAt:due.toISOString(),configFile,tokenFile:agentTokenFile};
  await writeFile(join(directory,'schedule-fixture.json'),JSON.stringify(record,null,2)+'\n'); console.log(JSON.stringify(record));
} finally { await app.close(); }
